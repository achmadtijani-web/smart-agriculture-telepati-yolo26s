"""Read-only diagnosis of class AP, training balance, object size and label conflicts."""
from __future__ import annotations
import argparse
from collections import Counter, defaultdict
import csv
import json
from pathlib import Path
import re
import statistics

ROOT = Path(__file__).resolve().parents[1]


def read(path):
    return json.loads(path.read_text(encoding='utf-8-sig'))


def write_csv(path, rows):
    with path.open('w',encoding='utf-8-sig',newline='') as handle:
        writer = csv.DictWriter(handle,fieldnames=list(rows[0]))
        writer.writeheader();writer.writerows(rows)


def audit(root, render=False, dataset_override=None, manifest_override=None):
    out = root/'reports/diagnostics'
    out.mkdir(parents=True,exist_ok=True)
    names = {x['yolo_id']:x['name'] for x in read(root/'reports/class_mapping.json')['classes']}
    reference=root/'reports/dataset_reference.json'
    dataset=dataset_override or (Path(read(reference)['target']) if reference.exists() else root/'data/yolo')
    areas = defaultdict(list);minimum_sides=defaultdict(list);image_counts=Counter();raw_counts=Counter()
    candidates=defaultdict(list);negative=0;duplicate_rows=0
    cache_path=dataset/'labels/train.cache'
    cached=[]
    if cache_path.is_file():
        import numpy as np
        # This is the trusted local cache generated by our own Ultralytics runs.
        cache=np.load(cache_path,allow_pickle=True).item()
        cached=cache['labels']
        assert len(cached)==8822
        original=read(root/'reports/dataset_audit.json')['prepared']['train']['classes']
        coco_to_yolo={x['coco_id']:x['yolo_id'] for x in read(root/'reports/class_mapping.json')['classes']}
        raw_counts.update({coco_to_yolo[x['coco_id']]:x['annotations'] for x in original})
    entries=cached if cached else sorted((dataset/'labels/train').glob('*.txt'))
    for entry in entries:
        if cached:
            assert entry['normalized'] and entry['bbox_format']=='xywh'
            label=Path(entry['im_file'])
            values=[(float(cid),*map(float,box)) for cid,box in zip(entry['cls'].reshape(-1),entry['bboxes'])]
        else:
            label=entry
            values = [tuple(map(float,line.split())) for line in label.read_text().splitlines() if line.strip()]
            for value in values:raw_counts[int(value[0])]+=1
        unique = sorted(set(values));duplicate_rows += len(values)-len(unique)
        if not unique:negative+=1
        for cid in set(int(value[0]) for value in unique):
            image_counts[cid]+=1
            candidates[cid].append((label.stem,unique))
        for cid,cx,cy,w,h in unique:
            areas[int(cid)].append(w*h*640*640);minimum_sides[int(cid)].append(min(w,h)*640)
    if cached:duplicate_rows=sum(raw_counts.values())-sum(map(len,areas.values()))
    directories = [root/'reports/submission_evaluation',root/'reports/evaluation']
    evaluation = next((p for p in directories if (p/'metrics.json').is_file()),None)
    metric_path = evaluation/'metrics.json' if evaluation else root/'reports/yolo26n_reference.json'
    perclass_path = evaluation/'per_class_metrics.csv' if evaluation else root/'reports/yolo26n_per_class.csv'
    metrics = read(metric_path)
    with perclass_path.open(encoding='utf-8-sig',newline='') as handle:
        scores = {int(x['class_id']):x for x in csv.DictReader(handle) if x['split']=='val'}
    rows=[]
    for cid,name in names.items():
        a=areas[cid];score=scores[cid]
        rows.append(dict(class_id=cid,class_name=name,train_images=image_counts[cid],train_boxes_effective=len(a),
            train_boxes_before_loader=raw_counts[cid],small32_percent=100*sum(x<1024 for x in a)/len(a),
            min_side8_percent=100*sum(x<8 for x in minimum_sides[cid])/len(a),median_area_px2=statistics.median(a),
            val_AP50_percent=100*float(score['ap50']),val_AP50_95_percent=100*float(score['ap50_95']),
            val_precision_percent=100*float(score['precision_iou50']),val_recall_percent=100*float(score['recall_iou50']),
            val_F1_percent=100*float(score['f1_iou50'])))
    write_csv(out/'class_balance_size_AP.csv',rows)
    manifest_path=manifest_override or root/'reports/manifest.csv'
    if not manifest_path.exists():manifest_path=root/'reports/reproduction_dataset/manifest.csv'
    if not manifest_path.exists():raise FileNotFoundError('Provide --manifest from prepare_dataset.py to inspect raw label conflicts')
    with manifest_path.open(encoding='utf-8-sig',newline='') as handle:
        manifest=list(csv.DictReader(handle))
    pixels=defaultdict(list)
    for x in manifest:pixels[x['pixel_sha256']].append(x)
    conflicts=[xs for xs in pixels.values() if len({x['label_sha256'] for x in xs})>1]
    raw_cache={};conflict_reports=[]
    for group_index,xs in enumerate(conflicts):
        examples=[]
        for x in xs:
            source=Path(x['source_path']);annotation=source.parent/'_annotations.coco.json'
            if annotation not in raw_cache:raw_cache[annotation]=read(annotation)
            coco=raw_cache[annotation];cat={c['id']:c['name'] for c in coco['categories']}
            labels=[dict(class_name=cat[a['category_id']],bbox=a['bbox']) for a in coco['annotations'] if str(a['image_id'])==x['image_id']]
            examples.append(dict(source_split=x['source_split'],source_file=x['source_file'],included=x['included']=='1',
                                 prepared_split=x['prepared_split'],labels=labels))
        conflict_reports.append(dict(pixel_sha256=xs[0]['pixel_sha256'],examples=examples,
            image=f'label_conflict_{group_index+1}.jpg',interpretation='Same decoded pixels but different annotation hashes; inspect actual classes and boxes before deciding if correction is needed.'))
        if render:
            from PIL import Image,ImageDraw,ImageFont
            canvas=Image.new('RGB',(640*len(xs),730),'#101820');d=ImageDraw.Draw(canvas)
            try:font=ImageFont.truetype('C:/Windows/Fonts/arial.ttf',18)
            except OSError:font=ImageFont.load_default(size=18)
            for index,(x,e) in enumerate(zip(xs,examples)):
                im=Image.open(x['source_path']).convert('RGB');draw=ImageDraw.Draw(im)
                for label in e['labels']:
                    bx,by,bw,bh=label['bbox'];draw.rectangle((bx,by,bx+bw,by+bh),outline='#ff4040',width=3)
                    draw.text((max(1,bx),max(1,by)),label['class_name'],fill='#ffffff',stroke_fill='#000000',stroke_width=2,font=font)
                canvas.paste(im,(640*index,85))
                caption=f"{e['source_split']} | included={e['included']} | {len(e['labels'])} boxes"
                d.text((640*index+8,8),caption,fill='white',font=font)
                d.text((640*index+8,34),e['source_file'][:55],fill='#b9c6cc',font=font)
            canvas.save(out/f'label_conflict_{group_index+1}.jpg',quality=92)
    aliases=defaultdict(list)
    for cid,name in names.items():aliases[re.sub('[^a-z0-9]','',name.lower())].append(dict(class_id=cid,name=name))
    aliases=[x for x in aliases.values() if len(x)>1]
    ordered=sorted(rows,key=lambda x:x['val_AP50_95_percent'])
    counts=[x['train_images'] for x in rows];boxes=[x['train_boxes_effective'] for x in rows]
    result=dict(status='complete',scope='Training-only image balance/box sizes; validation AP used for diagnosis. No labels/splits changed.',
        evaluated_weights_sha256=metrics['weights_sha256'],evaluation_source=metric_path.relative_to(root).as_posix(),
        selected_confidence=metrics['selected_confidence'],classes=rows,weakest_validation_classes=ordered[:6],
        training_statistics_source='trusted Ultralytics label cache used by these training runs' if cached else 'prepared YOLO text labels',
        image_imbalance_ratio=max(counts)/min(counts),box_imbalance_ratio=max(boxes)/min(boxes),
        train_effective_boxes=sum(boxes),duplicate_training_label_rows_removed=duplicate_rows,negative_train_images=negative,
        small32_percent=100*sum(sum(x<1024 for x in a) for a in areas.values())/sum(boxes),
        name_alias_candidates=aliases,identical_pixel_label_conflicts=conflict_reports,
        note='Alias names do not prove semantic equivalence. Retain18 classes and fixed evaluation labels until an expert approves a consistent annotation policy.')
    (out/'diagnosis.json').write_text(json.dumps(result,indent=2),encoding='utf-8')
    lines=['# Diagnosis data dan model sesuai arahan dosen','',
        f"Sumber metrik: `{result['evaluation_source']}`. Analisis perbaikan menggunakan **validation**, bukan test untuk memilih percobaan baru.",'',
        '## 1. AP per kelas dan confusion matrix','',
        '| Kelas | Gambar train | Kotak efektif | AP50 val | AP50–95 val | Recall val | Kotak <32² px |',
        '|---|---:|---:|---:|---:|---:|---:|']
    for row in ordered:
        lines.append(f"| {row['class_name']} | {row['train_images']} | {row['train_boxes_effective']} | {row['val_AP50_percent']:.2f}% | {row['val_AP50_95_percent']:.2f}% | {row['val_recall_percent']:.2f}% | {row['small32_percent']:.2f}% |")
    lines += ['', 'Matriks bawaan evaluasi AP memakai confidence0.001 dan IoU pencocokan0.45. Itu bukan matriks pada threshold operasional. Matriks operasional validation dibuat terpisah pada confidence pilihan F1 dan IoU0.50; sumbu baris=prediksi, kolom=label sebenarnya, dengan background untuk FP/FN.', '',
        '## 2. Kualitas label','',
        f"Ditemukan **{len(conflict_reports)} kelompok gambar dengan piksel identik tetapi hash anotasi berbeda**. Salah satunya menunjukkan Leaf Scald dengan tiga kotak gejala versus Leaf scald dengan satu kotak daun. Anggota train yang bertabrakan dengan test telah dikeluarkan dari train; tidak ada kebocoran lintas split yang dipertahankan melalui kelompok itu. Perbedaan lain perlu diperiksa berdasarkan koordinat aktual, bukan dianggap otomatis salah.",'',
        'Pasangan nama yang perlu kebijakan anotasi: '+ '; '.join('/'.join(x['name'] for x in group) for group in aliases)+'. Nama mirip tidak cukup untuk menggabungkan kelas. Tentukan dahulu objek target (lesi/daun/bulir), definisi penyakit, dan kebijakan satu atau banyak kotak.', '',
        '## 3. Keseimbangan dan penambahan data','',
        f"Rasio gambar kelas terbanyak/tersedikit **{result['image_imbalance_ratio']:.2f}×**, rasio kotak **{result['box_imbalance_ratio']:.2f}×**. Gambar, jumlah sumber/sesi, dan kepadatan kotak perlu dipisahkan: banyak lesi pada sedikit foto bukan keragaman sampel yang tinggi.",'',
        '`Brown spot` memiliki1.622 baris kotak train pada259 gambar; rendahnya AP bukan semata kekurangan kotak. `Leaf scald` memiliki147 gambar train, sehingga pengumpulan foto baru yang independen lebih berguna daripada sekadar menduplikasi fotonya.', '',
        'Prioritaskan foto train baru dari sesi/lahan beragam untuk kelas lemah. Augmentasi dan oversampling hanya pada train, berbasis gambar/sumber, dengan batas pengulangan; pertahankan box dan warna gejala, audit hasilnya, dan jangan menambah salinan validation/test ke train. Oversampling dapat ikut menggandakan kelas lain pada foto yang sama.', '',
        '## 4. Resolusi','',
        f"Semua gambar tersimpan640×640. **{result['small32_percent']:.2f}%** kotak train berluas di bawah32² piksel. Resolusi768 sudah dicoba pada fine-tune YOLO11s. Ini membesarkan input1.2× per sisi, tetapi tidak mengembalikan detail yang sudah hilang pada sumber640. Untuk gejala sangat kecil, pertimbangkan foto asli lebih tinggi atau crop/tiling beranotasi yang benar; seluruh turunan satu foto harus tetap satu split.",'',
        '## 5. Threshold F1','',
        f"Confidence **{metrics['selected_confidence']:.9f}** dipilih dari puncak kurva macro-F1 validation, lalu diterapkan ke test. AP dihitung sepanjang kurva confidence. F1 formulir adalah rata-rata F1 per kelas pada IoU0.50; bukan F1 yang dihitung dari rata-rata precision/recall.",'',
        '## 6. Perbandingan arsitektur','',
        'YOLO26s dan YOLO11s sudah dibandingkan dengan data dan18 kelas yang sama. Tambahan epoch serta input768 membuat anggaran berbeda, sehingga gain tidak diatribusikan ke arsitektur saja. RF-DETR/D-FINE perlu uji GPU dan pengukuran validation dengan protokol yang sama sebelum dianggap lebih baik. Default resolusi RF-DETR kecil tidak boleh langsung dianggap cocok untuk lesi kecil.', '',
        'Keputusan label tidak diotomatisasi dari skor test. Audit ini tidak mengubah anotasi, identitas kelas, atau data evaluasi.']
    resolution=root/'reports/resolution_ablation/selection.json'
    if resolution.exists():
        study=read(resolution)
        lines += ['', '## Uji resolusi terkontrol pada bobot yang sama','',
            '| Input | Val mAP50 | Val mAP50–95 | Val macro-F1 | Confidence dari val |',
            '|---|---:|---:|---:|---:|']
        for x in study['results']:
            lines.append(f"| {x['imgsz']} | {x['mAP50']*100:.2f}% | {x['mAP50_95']*100:.2f}% | {x['macro_f1']*100:.2f}% | {x['selected_confidence']:.4f} |")
        lines += ['',f"Input operasional terpilih: **{study['winner']['imgsz']}** berdasarkan validation mAP50–95. Tidak ada angka test yang dipakai untuk memilih resolusi. Angka F1 pada tabel adalah validation, bukan isian test formulir."]
    operating=root/'reports/diagnostics_operating_val/summary.json'
    if operating.exists():
        cm=read(operating)
        lines += ['', '## Kesalahan kelas pada threshold operasional','',
            f"Matriks validation: confidence **{cm['confidence']:.6f}**, IoU matching **0.50**, input **{cm['imgsz']}**. {cm['unmatched_ground_truth']} kotak rujukan tidak terpasangkan; {cm['unmatched_predictions']} prediksi tidak terpasangkan. Kesalahan kelas pada kotak yang cocok dipisahkan dari kedua hitungan itu.",'',
            '| Kelas sebenarnya | Diprediksi sebagai | Kotak |','|---|---|---:|']
        for pair in cm['top_class_confusions'][:10]:
            lines.append(f"| {pair['actual_class']} | {pair['predicted_class']} | {pair['count']} |")
        lines += ['', '[Confusion matrix operasional](../reports/diagnostics_operating_val/confusion_matrix_normalized.png). Pencocokan matriks dilakukan lintas kelas secara greedy berdasarkan IoU; AP/F1 resmi memakai pencocokan per kelas sepanjang kurva. Jangan mengganti F1 formulir dengan perhitungan dari matriks diagnosis ini.']
        matrix_path=operating.parent/'confusion_matrix_counts.csv'
        with matrix_path.open(encoding='utf-8-sig',newline='') as handle:raw=list(csv.reader(handle))
        matrix=[[int(float(v)) for v in row[1:]] for row in raw[1:]]
        errors=[]
        for cid in range(18):
            support=sum(row[cid] for row in matrix);tp=matrix[cid][cid];missed=matrix[18][cid]
            errors.append(dict(class_id=cid,class_name=names[cid],gt_instances=support,correct=tp,
                missed=missed,wrong_class=support-tp-missed,unmatched_predictions=matrix[cid][18]))
        write_csv(operating.parent/'per_class_error_counts.csv',errors)
        wrong=sum(x['wrong_class'] for x in errors)
        lines += ['',f"Dari4.758 kotak validation, **{cm['unmatched_ground_truth']} terlewat** dan **{wrong} cocok dengan kelas keliru**. Pada konfigurasi ini, kotak terlewat adalah komponen kesalahan yang lebih besar daripada pertukaran kelas.",'',
            '| Kelas | Kotak val | Terlewat | Kelas keliru |','|---|---:|---:|---:|']
        for row in sorted(errors,key=lambda x:x['missed'],reverse=True)[:6]:
            lines.append(f"| {row['class_name']} | {row['gt_instances']} | {row['missed']} | {row['wrong_class']} |")
    comparison=root/'reports/validation_candidates/comparison.json'
    if comparison.exists():
        study=read(comparison)
        lines += ['', '## Kandidat dibandingkan pada protokol validation yang sama','',
            '| Model | Input | Total epoch | Val mAP50 | Val mAP50–95 | Val macro-F1 | Confidence F1 |',
            '|---|---:|---:|---:|---:|---:|---:|']
        for model in study['models']:
            lines.append(f"| {model['name']} | {model['imgsz']} | {model['total_training_epochs']} | {model['mAP50']*100:.2f}% | {model['mAP50_95']*100:.2f}% | {model['macro_F1']*100:.2f}% | {model['selected_confidence']:.4f} |")
        lines += ['',f"Pemenang agregat validation mAP50–95: **{study['winner']}**. Lihat `reports/validation_candidates/per_class_comparison.csv` untuk54 baris perbandingan per kelas. Dataset, jumlah kelas, confidence floor AP, NMS, batas deteksi, dan batch evaluasi sama; ukuran input, resep serta anggaran training berbeda dan dicatat. Ini membandingkan konfigurasi keseluruhan, bukan ablation arsitektur murni."]
    pilot=root/'rfdetr_trial/pilot_status_b8_g2.json'
    if pilot.exists() and read(pilot).get('status')=='complete':
        trial=read(pilot)
        lines += ['', '## RF-DETR: kelayakan telah diuji, akurasi belum dibandingkan penuh','',
            f"RF-DETR Nano1.9.0 berhasil menjalankan satu epoch pilot:148 gambar train,74 validation, tanpa test. Input640, batch8, akumulasi2, gradient checkpointing. Puncak alokasi GPU{trial['peak_allocated_MiB']:.0f}MiB, cadangan allocator{trial['peak_reserved_MiB']:.0f}MiB pada RTX4050 Laptop6GB.",'',
            f"Estimasi12 epoch full train dari pilot sekitar{trial['estimated_12_epoch_training_hours']:.1f}jam, belum termasuk validation penuh dan penulisan checkpoint; alokasi praktis sekitar6–8jam. Estimasi bukan jaminan waktu. Pengguna memilih finalisasi YOLO26s dan audit untuk tenggat submission. RF-DETR tidak diberi skor pembanding final dari pilot kecil ini.",'',
            'RF-DETR/varian yang lebih besar maupun D-FINE tidak otomatis lebih baik pada lesi kecil atau label yang tidak konsisten. Untuk percobaan berikutnya, gunakan split/kelas yang sama, evaluasi per kelas, dan anggaran yang dicatat. [Sumber RF-DETR](https://github.com/roboflow/rf-detr), [sumber D-FINE](https://github.com/Peterande/D-FINE).']
    (root/'docs/DIAGNOSIS_DATA_MODEL.md').write_text('\n'.join(lines)+'\n',encoding='utf-8')
    print(json.dumps(dict(status='complete',classes=18,weakest=[x['class_name'] for x in ordered[:4]],
                         image_imbalance_ratio=result['image_imbalance_ratio'],small32_percent=result['small32_percent'],
                         conflict_groups=len(conflict_reports))))


if __name__=='__main__':
    parser=argparse.ArgumentParser();parser.add_argument('--root',type=Path,default=ROOT);parser.add_argument('--render',action='store_true')
    parser.add_argument('--dataset-dir',type=Path);parser.add_argument('--manifest',type=Path)
    args=parser.parse_args();audit(args.root.resolve(),args.render,args.dataset_dir,args.manifest)
